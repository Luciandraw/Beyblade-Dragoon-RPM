"""Export the firmware's screen assets for the web screen emulator.

Writes docs/screen-assets.mjs with the Adafruit GFX classic 5x7 font
(printable ASCII only) and the boot logo / blade icon bitmaps from main/.
Re-run after changing a bitmap header:

    python scripts/export-screen-assets.py path/to/Adafruit_GFX_Library/glcdfont.c
"""
import base64
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent


def byte_array(source, name):
    body = re.search(name + r"\[\]\s*PROGMEM\s*=\s*\{(.*?)\};", source, re.S).group(1)
    return bytes(int(value, 16) for value in re.findall(r"0x[0-9A-Fa-f]{2}", body))


def bitmap(header, prefix):
    source = (root / "main" / header).read_text(encoding="utf8")
    width = int(re.search(prefix + r"_WIDTH\s*=\s*(\d+)", source).group(1))
    height = int(re.search(prefix + r"_HEIGHT\s*=\s*(\d+)", source).group(1))
    data = byte_array(source, prefix + "_BITMAP")
    assert len(data) == (width + 7) // 8 * height, header
    return width, height, base64.b64encode(data).decode()


font_source = pathlib.Path(sys.argv[1]).read_text(encoding="utf8")
font = byte_array(font_source, r"font")
assert len(font) >= 256 * 5
printable = base64.b64encode(font[32 * 5:127 * 5]).decode()
logo = bitmap("logo_bitmap.h", "BOOT_LOGO")
blade = bitmap("blade_icon.h", "BLADE_ICON")

(root / "docs" / "screen-assets.mjs").write_text(
    "// Generated by scripts/export-screen-assets.py from the firmware sources. Do not edit.\n"
    "// Font: Adafruit GFX classic 5x7 font, (c) 2012 Adafruit Industries, BSD License.\n"
    f"export const FONT_FIRST = 32;\nexport const FONT = '{printable}';\n"
    f"export const BOOT_LOGO = {{width: {logo[0]}, height: {logo[1]}, data: '{logo[2]}'}};\n"
    f"export const BLADE_ICON = {{width: {blade[0]}, height: {blade[1]}, data: '{blade[2]}'}};\n",
    encoding="utf8", newline="\n")
print("wrote docs/screen-assets.mjs")
